function dayNumber(day: number): string {
  const glyphs = String(day)
    .split('')
    .map((ch) => DIGITS[Number(ch)])
  const first = glyphs[0]
  const last = glyphs[glyphs.length - 1]
  const advance = glyphs.slice(0, -1).reduce((sum, g) => sum + g[0], 0)
  const inkWidth = advance + last[2] - first[1]
  let x = NUMBER_CENTER - inkWidth / 2 - first[1]
  let out = ''
  for (const [adv, , , d] of glyphs) {
    out += `<path transform="translate(${x.toFixed(2)} 226.43)" d="${d}"/>`
    x += adv
  }
  return out
}
